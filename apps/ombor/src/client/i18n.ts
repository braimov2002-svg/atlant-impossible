export type Key = keyof typeof T;
export type Tr = (key: Key) => string;

export const translator =
  (lang: Lang): Tr =>
  (key) =>
    T[key][lang === 'ru' ? 1 : 0];

const FIELDS: Record<string, Key> = {
  login: 'login', name: 'full_name', date: 'date', object: 'object', items: 'items', item_name: 'item_name',
  qty: 'qty', price: 'price', amount: 'amount', lines: 'qty', number: 'number', from: 'date', to: 'date',
  vehicle_date: 'vehicle_date', role: 'role',
};

/** Turns a server error code into a sentence the user can act on. */
export function errorText(e: unknown, t: Tr): string {
  const code = e instanceof Error ? e.message : 'server_error';
  const [kind, field] = code.split(':');
  if (kind === 'required' || kind === 'invalid') {
    const label = FIELDS[field] ? t(FIELDS[field]) : field;
    return `${t(kind === 'required' ? 'e_required' : 'e_invalid')}: ${label}`;
  }
  const key = `e_${code}` as Key;
  return key in T ? t(key) : t('e_server_error');
}
