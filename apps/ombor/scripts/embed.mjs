// Packs the built site into the Worker itself, for publishing from places
// where Cloudflare's separate asset upload cannot be used (it signs each
// upload with its own short-lived key, which some network proxies replace).
// Writes .embedded/: the files, a worker that serves them, and its config.
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = join(root, 'dist');
const out = join(root, '.embedded');
const TYPES = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.png': 'image/png', '.webp': 'image/webp',
  '.svg': 'image/svg+xml', '.ttf': 'font/ttf', '.ico': 'image/x-icon',
};

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });

rmSync(out, { recursive: true, force: true });
mkdirSync(out);
const files = walk(dist);
files.forEach((path, i) => cpSync(path, join(out, `f${i}.bin`)));

writeFileSync(
  join(out, 'worker.ts'),
  `// Generated by scripts/embed.mjs. Do not edit.
import api from '../src/server/index';
${files.map((_, i) => `import f${i} from './f${i}.bin';`).join('\n')}

const FILES: Record<string, [ArrayBuffer, string]> = {
${files.map((p, i) => `  ${JSON.stringify('/' + relative(dist, p).split('\\').join('/'))}: [f${i}, ${JSON.stringify(TYPES[extname(p)] ?? 'application/octet-stream')}],`).join('\n')}
};

export default {
  fetch(request: Request, env: unknown, ctx: ExecutionContext) {
    const { pathname } = new URL(request.url);
    if (pathname.startsWith('/api/')) return api.fetch(request, env as never, ctx);
    if (request.method !== 'GET' && request.method !== 'HEAD') return new Response(null, { status: 405 });
    // Any other address is a page of the app: the app itself decides what to show.
    const [body, type] = FILES[pathname] ?? FILES['/index.html'];
    return new Response(request.method === 'HEAD' ? null : body, {
      headers: {
        'content-type': type,
        // Built files carry a hash in their name and never change; pages are always re-checked.
        'cache-control': pathname.startsWith('/assets/') ? 'public, max-age=31536000, immutable' : 'no-cache',
        'x-content-type-options': 'nosniff',
      },
    });
  },
};
`,
);

const config = JSON.parse(readFileSync(join(root, 'wrangler.jsonc'), 'utf8'));
delete config.assets;
delete config.$schema;
config.main = 'worker.ts';
config.rules = [{ type: 'Data', globs: ['**/*.bin'], fallthrough: false }];
config.d1_databases[0].migrations_dir = '../migrations';
writeFileSync(join(out, 'wrangler.json'), JSON.stringify(config, null, 2));
console.log(`embedded ${files.length} files`);
